    function annotateWithNajia(result, hexNum, lowerTrigram, upperTrigram,
                               dayStem, dayGanzhiIndex, monthZhi) {
      /* 给 result['yaos'] 逐爻补全纳甲信息，并盖章世应/旬空/宫卦/日干支/月建等 */
      var palaceEntry = HEXAGRAM_PALACE[hexNum] || [lowerTrigram, 1];
      var palaceTrig = palaceEntry[0];
      var wl = getWorldLine(hexNum);
      var worldPos = wl[0], appPos = wl[1];
      var kongWangBranches = getKongWang(dayGanzhiIndex);
      var liuShenList = assignLiuShen(dayStem);
      var dayZhi = DIZHI[dayGanzhiIndex % 12];

      var yaos = result["yaos"] || [];
      var enrichedYaos = [];

      for (var i = 0; i < yaos.length; i++) {
        var yao = yaos[i];
        var pos = i + 1;
        var trigram, branch;
        if (pos <= 3) {
          trigram = lowerTrigram;
          var inner = (NAJIA_BRANCHES[trigram] || { "inner": ["子", "寅", "辰"] }).inner;
          branch = inner[i];
        } else {
          trigram = upperTrigram;
          var outer = (NAJIA_BRANCHES[trigram] || { "outer": ["午", "申", "戌"] }).outer;
          branch = outer[i - 3];
        }

        var gan = (NAJIA_STEM[trigram] || {})[(pos <= 3) ? "inner" : "outer"];
        if (gan === undefined) gan = "";
        var wx = DIZHI_WUXING[branch];
        if (wx === undefined) wx = "土";
        var liuQin = getLiuQin(palaceTrig, branch);
        var liuShen = liuShenList[i];
        var isKongWang = kongWangBranches.indexOf(branch) !== -1;
        var strength = getLineStrength(branch, monthZhi);
        var isWorld = (pos === worldPos);
        var isApplication = (pos === appPos);
        var isYuePo = LIUCHONG[branch] === monthZhi;      // 月破
        var isRiChong = LIUCHONG[branch] === dayZhi;      // 日冲

        enrichedYaos.push(Object.assign({}, yao, {
          "gan": gan,                    // 纳甲天干
          "najia": gan + branch,         // 完整纳甲，如 "甲子"
          "branch": branch,
          "element": wx,
          "liu_qin": liuQin,
          "liu_shen": liuShen,
          "liu_shen_meaning": LIU_SHEN_MEANINGS[liuShen] || {},
          "liu_qin_meaning": LIU_QIN_MEANINGS[liuQin] || {},
          "kong_wang": isKongWang,
          "yue_po": isYuePo,
          "ri_chong": isRiChong,
          "strength": strength,
          "is_world": isWorld,
          "is_application": isApplication,
        }));
      }

      result["yaos"] = enrichedYaos;
      result["world_line"] = worldPos;
      result["application_line"] = appPos;
      result["kong_wang_branches"] = kongWangBranches;
      result["palace_trigram"] = palaceTrig;
      result["palace_element"] = PALACE_ELEMENT[palaceTrig] || "金";
      result["najia_summary"] = buildNajiaSummary(enrichedYaos, worldPos, appPos, kongWangBranches);

      // ── 时空信息 ──
      result["day_ganzhi"] = dayStem + dayZhi;         // 日干支，如 癸亥
      result["day_ganzhi_index"] = dayGanzhiIndex;
      result["month_zhi"] = monthZhi;                  // 月建，如 酉
      result["hex_type"] = classifyHexagram(hexNum);

      // ── 之卦纳甲 ──
      annotateChangedHexagram(result, dayStem, dayGanzhiIndex, monthZhi);
      return result;
    }

