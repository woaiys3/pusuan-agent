    function linesToTrigramName(lines) {
      /* 3 根爻线（自下而上）→ 卦名 */
      for (var name in TRIGRAMS) {
        var tg = TRIGRAMS[name].lines;
        if (tg[0] === lines[0] && tg[1] === lines[1] && tg[2] === lines[2]) return name;
      }
      throw new Error("No trigram for lines " + JSON.stringify(lines));
    }

    function hexagramNumber(lower, upper) {
      /* (下卦, 上卦) → 文王卦序编号 */
      for (var num in HEXAGRAM_TRIGRAM_MAPPING) {
        var pair = HEXAGRAM_TRIGRAM_MAPPING[num];
        if (pair[0] === lower && pair[1] === upper) return parseInt(num, 10);
      }
      throw new Error("No hexagram for (" + lower + ", " + upper + ")");
    }

    function buildHexagramDict(num) {
      /* 按卦序编号构造可序列化的卦象 dict */
      var data = HEXAGRAM_DATA[num];
      var pair = HEXAGRAM_TRIGRAM_MAPPING[num];
      var lowerName = pair[0], upperName = pair[1];
      var upper = Object.assign({}, TRIGRAMS[upperName], { "name": upperName });
      var lower = Object.assign({}, TRIGRAMS[lowerName], { "name": lowerName });
      return {
        "number": num,
        "name": data["name"],
        "upper": upper,
        "lower": lower,
        "judgment": data["judgment"],
        "image": data.hasOwnProperty("image") ? data["image"] : "",
        "lines": data.hasOwnProperty("lines") ? data["lines"] : {},
        "interpretation": data.hasOwnProperty("interpretation") ? data["interpretation"] : "",
      };
    }

    function getChangedHexagram(yaos, origLower, origUpper) {
      /* 老阴/老阳动爻翻转 → 之卦；无动爻返回 null */
      var hasChanging = false;
      for (var i = 0; i < yaos.length; i++) {
        if (isChanging(yaos[i])) { hasChanging = true; break; }
      }
      if (!hasChanging) return null;

      var changedLines = [];
      for (var j = 0; j < yaos.length; j++) {
        var line = yaotypeToLine(yaos[j]);
        if (isChanging(yaos[j])) {
          line = (line === LINE.YANG) ? LINE.YIN : LINE.YANG;  // 翻转
        }
        changedLines.push(line);
      }
      var newLowerName = linesToTrigramName(changedLines.slice(0, 3));
      var newUpperName = linesToTrigramName(changedLines.slice(3, 6));
      var newNum = hexagramNumber(newLowerName, newUpperName);
      return buildHexagramDict(newNum);
    }

    function coinDivination(yaoValues) {
      /* 三枚铜钱：每枚 0(字)/1(背)，三枚和 → 6老阴 7少阳 8少阴 9老阳。
         若显式给出 6 个爻值（6/7/8/9）则直接使用。 */
      var yaos;
      if (yaoValues && yaoValues.length === 6) {
        var map = { 6: YAO.LAO_YIN, 7: YAO.SHAO_YANG, 8: YAO.SHAO_YIN, 9: YAO.LAO_YANG };
        yaos = [];
        for (var i = 0; i < 6; i++) yaos.push(map[yaoValues[i]]);
      } else {
        yaos = [];
        var coinMap = { 0: YAO.LAO_YIN, 1: YAO.SHAO_YANG, 2: YAO.SHAO_YIN, 3: YAO.LAO_YANG };
        for (var k = 0; k < 6; k++) {
          var heads = _randInt(0, 1) + _randInt(0, 1) + _randInt(0, 1);
          yaos.push(coinMap[heads]);
        }
      }
      return makeResult("coin", yaos);
    }

    function yarrowDivination() {
      /* 蓍草法，概率分布正确：9(老阳)=3/16  8(少阴)=7/16  7(少阳)=5/16  6(老阴)=1/16 */
      var weights = [1, 5, 7, 3];   // 老阴 少阳 少阴 老阳
      var types = [YAO.LAO_YIN, YAO.SHAO_YANG, YAO.SHAO_YIN, YAO.LAO_YANG];
      var yaos = [];
      for (var i = 0; i < 6; i++) {
        var r = _rand() * 16;
        var idx = r < 1 ? 0 : r < 6 ? 1 : r < 13 ? 2 : 3;
        yaos.push(types[idx]);
      }
      return makeResult("yarrow", yaos);
    }

    function timeDivination(dt) {
      /* 时间起卦：
         上卦数 = (y+m+d) % 8 or 8
         下卦数 = (y+m+d+h) % 8 or 8
         动爻   = (y+m+d+h) % 6 or 6（1-based） */
      if (dt === null || dt === undefined) dt = new Date();
      var y, m, d, h;
      if (dt instanceof Date) {
        y = dt.getFullYear(); m = dt.getMonth() + 1; d = dt.getDate(); h = dt.getHours();
      } else {
        y = dt.y; m = dt.m; d = dt.d; h = dt.h || 0;
      }

      var upperNum = ((y + m + d) % 8) || 8;
      var lowerNum = ((y + m + d + h) % 8) || 8;
      var changePos = ((y + m + d + h) % 6) || 6;  // 1-based

      var upperName = KING_WEN_TRIGRAM[upperNum];
      var lowerName = KING_WEN_TRIGRAM[lowerNum];
      var upperTg = TRIGRAMS[upperName];
      var lowerTg = TRIGRAMS[lowerName];

      // 6 根爻线（下卦三爻 + 上卦三爻，自下而上）
      var sixLines = lowerTg.lines.concat(upperTg.lines);

      var yaos = [];
      for (var i = 0; i < sixLines.length; i++) {
        var pos = i + 1;
        var line = (sixLines[i] === "阳") ? LINE.YANG : LINE.YIN;
        if (pos === changePos) {
          yaos.push((line === LINE.YANG) ? YAO.LAO_YANG : YAO.LAO_YIN);
        } else {
          yaos.push((line === LINE.YANG) ? YAO.SHAO_YANG : YAO.SHAO_YIN);
        }
      }
      return makeResult("time", yaos);
    }

    function manualDivination(yaoValues) {
      /* 显式给出 6 个爻值（6/7/8/9，自初爻到上爻） */
      return coinDivination(yaoValues);
    }

    function makeResult(method, yaos) {
      /* 内部结果构造：本卦/之卦/动爻/六爻明细 */
      var lowerLines = [];
      var upperLines = [];
      for (var i = 0; i < 3; i++) lowerLines.push(yaotypeToLine(yaos[i]));
      for (var j = 3; j < 6; j++) upperLines.push(yaotypeToLine(yaos[j]));

      var lowerName = linesToTrigramName(lowerLines);
      var upperName = linesToTrigramName(upperLines);
      var origNum = hexagramNumber(lowerName, upperName);

      var original = buildHexagramDict(origNum);
      var changed = getChangedHexagram(yaos, lowerName, upperName);

      var changingLines = [];
      for (var k = 0; k < yaos.length; k++) {
        if (isChanging(yaos[k])) changingLines.push(k + 1);
      }

      var yaoDetails = [];
      for (var n = 0; n < yaos.length; n++) {
        var lineData = HEXAGRAM_DATA[origNum]["lines"][n + 1];
        if (lineData === undefined) lineData = "";
        yaoDetails.push({
          "position": n + 1,
          "yao_type": yaos[n],
          "line": yaotypeToLine(yaos[n]),
          "is_changing": isChanging(yaos[n]),
          "description": lineData,
        });
      }

      return {
        "method": method,
        "original": original,
        "changed": changed,
        "changing_lines": changingLines,
        "yaos": yaoDetails,
      };
    }

