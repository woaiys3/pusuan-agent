    // 工具层中文起卦方式 → core 方法名
    var MODE_MAP = {
      "铜钱": "coin",
      "蓍草": "yarrow",
      "时间": "time",
      "手动": "manual",
    };
    var MODE_NAMES = "铜钱、蓍草、时间、手动";

    function isInt(v) {
      return typeof v === "number" && Number.isInteger(v);
    }

    function isDt(dt) {
      /* 公历时间校验：{y,m,d,h} 为整数；i 可缺省（时间起卦只用到小时） */
      if (!dt || typeof dt !== "object" || Array.isArray(dt)) return false;
      if (!(isInt(dt.y) && isInt(dt.m) && isInt(dt.d) && isInt(dt.h))) return false;
      return (dt.i === undefined || dt.i === null || isInt(dt.i));
    }

    function resolveIntent(raw) {
      /* 把工具层传入的「意图参数」解析为 qigua 参数。
         method: 铜钱/蓍草/时间/手动（缺省「铜钱」）
         dt:     时间起卦模式 {y,m,d,h,i}（缺省=当前时间）
         yao_values: 手动/铜钱模式 6 个爻值（6=老阴 7=少阳 8=少阴 9=老阳，从初爻到上爻）
         非法参数抛 Error（对应 Python ValueError）。 */
      raw = Object.assign({}, raw || {});
      var methodRaw = String(raw.method || "铜钱").trim();
      var method = MODE_MAP[methodRaw];
      if (!method) {
        throw new Error("未知起卦方式: " + methodRaw + "，可选 " + MODE_NAMES);
      }

      var dt = raw.dt;
      if (dt !== undefined && dt !== null && !isDt(dt)) {
        throw new Error("dt 须为公历时间 {y,m,d,h,i}（i 可缺省）");
      }

      var yaoValues = raw.yao_values;
      if (yaoValues !== undefined && yaoValues !== null) {
        var ok = Array.isArray(yaoValues) && yaoValues.length === 6;
        if (ok) {
          for (var i = 0; i < 6; i++) {
            if (!(yaoValues[i] === 6 || yaoValues[i] === 7 ||
                  yaoValues[i] === 8 || yaoValues[i] === 9)) { ok = false; break; }
          }
        }
        if (!ok) {
          throw new Error("yao_values 须为 6 个爻值（6=老阴 7=少阳 8=少阴 9=老阳，从初爻到上爻）");
        }
      }

      if (method === "manual" && !yaoValues) {
        throw new Error("手动模式需要 yao_values（6 个爻值：6=老阴 7=少阳 8=少阴 9=老阳，从初爻到上爻）");
      }

      return { "method": method, "dt": dt, "yao_values": yaoValues };
    }

    function _pad2(n) {
      return (n < 10 ? "0" : "") + n;
    }

    function qigua(method, dt, yaoValues, seed) {
      /* 六爻起卦 + 纳甲装卦，返回完整卦象对象（字段与 Python 版完全一致）。
         method: coin / yarrow / time / manual
         dt:     null=当前时间；或 {y,m,d,h,i}（时间起卦的卦象与纳甲日干支/月建均按此时间）
         yaoValues: 手动/铜钱模式显式指定的 6 个爻值（6/7/8/9）
         seed:   随机种子（可复现，供测试；工具层不暴露给 AI） */
      if (seed !== undefined && seed !== null) {
        _seedRandom(seed);
      }
      if (dt !== null && dt !== undefined && typeof dt === "object" && !(dt instanceof Date)) {
        dt = new Date(dt.y, (dt.m || 1) - 1, dt.d || 1, dt.h || 0, dt.i || 0);
      }
      if (dt === null || dt === undefined) {
        dt = new Date();
      }

      var result;
      if (method === "coin") {
        result = coinDivination(yaoValues);
      } else if (method === "yarrow") {
        result = yarrowDivination();
      } else if (method === "time") {
        result = timeDivination(dt);
      } else if (method === "manual") {
        if (!yaoValues) {
          throw new Error("manual 模式需要 6 个爻值 (6/7/8/9)");
        }
        result = manualDivination(yaoValues);
      } else {
        throw new Error("未知起卦方式: " + method + "，可选 " + MODE_NAMES);
      }

      // 纳甲装卦：日干支/月建统一按起卦时间 dt 推算（含 1900-01-01 基准的 60 甲子日）
      var dayIdx = _dayGanzhiIndex(dt);
      var gz = ganzhiFromIndex(dayIdx);
      var dayGan = gz[0];
      var monthZhi = monthZhiOf(dt);   // 月建按「十二节」定取（nongli.js sTerm 天文精确）
      annotateWithNajia(
        result, result["original"]["number"],
        result["original"]["lower"]["name"],
        result["original"]["upper"]["name"],
        dayGan, dayIdx, monthZhi
      );
      result["qigua_time"] = dt.getFullYear() + "-" + _pad2(dt.getMonth() + 1) + "-" +
                             _pad2(dt.getDate()) + " " + _pad2(dt.getHours()) + ":" +
                             _pad2(dt.getMinutes());
      // 手动/铜钱共用 coin_divination 内部标记为 coin，驱动层按实际方式覆盖
      result["method"] = method;
      return result;
    }

    function _dayGanzhiIndex(dt) {
      /* (1900-01-01 基准 + 距今天数) % 60；用 UTC 日历日差，时区无关 */
      var a = Date.UTC(dt.getFullYear(), dt.getMonth(), dt.getDate());
      var b = Date.UTC(1900, 0, 1);
      var days = Math.round((a - b) / 86400000);
      return (((REF_DAY_IDX + days) % 60) + 60) % 60;
    }

